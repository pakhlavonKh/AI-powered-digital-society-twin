"""Experimental unit-fixture membership sidecars; no production linker or I/O.

Uses the existing ResidentExtension / ExtensionRecord / AttributeValue shape.
The registry-driven ExtensionStore does not yet accept this experimental method;
no alternate store or automatic persistence is provided here.
"""
from collections import Counter
from collections.abc import Mapping
from dataclasses import asdict
import json

from pydantic import Field, StrictBool, ValidationError

from societytwin.common import canonical_hash
from societytwin.enrichment import SCHEMA_VERSION
from societytwin.enrichment.model import (
    AttributeValue, EnrichmentConfig, ExtensionRecord, ResidentExtension,
)
from societytwin.households.reconciliation import reconcile
from societytwin.national.dependencies import TypedModel
from societytwin.national.rng import STREAM_VERSION, Stream

METHOD_VERSION = 'fixture_capacity_shuffle_v1'
CONTRACT_VERSION = 'household-membership-1'
FIXTURE_PURPOSE = 'synthetic_fixture_only'
LIMITATIONS = (
    'Experimental synthetic fixture membership; not representative Ankara statistics.',
    'Random capacity allocation supplies no family roles, household type or demographic relationships.',
    'Production weighted linkage and persistence remain disabled.',
)


class MembershipError(ValueError):
    def __init__(self, message, report=None):
        super().__init__(message)
        self.report = report


class FixtureMembershipContract(TypedModel):
    """Caller-authored assertions for invented fixtures, never inferred approvals.

    Fingerprints are generated by input_fingerprints after the fixture is final.
    A reference documents the test's eligibility assertion, not official evidence.
    Every resident in this narrow contract must be eligible; subsets are unsupported.
    """
    contract_version: str = Field(pattern=r'^household-membership-1$')
    purpose: str = Field(pattern=r'^synthetic_fixture_only$')
    population_id: str = Field(min_length=1)
    household_population_id: str = Field(min_length=1)
    resident_representation: str = Field(pattern=r'^unit_person_records$')
    household_representation: str = Field(pattern=r'^unit_household_records$')
    universe_approved: StrictBool
    eligibility_source_ref: str = Field(min_length=1)
    eligible_resident_ids: tuple[str, ...] = Field(min_length=1)
    resident_input_sha256: str = Field(pattern=r'^[0-9a-f]{64}$')
    household_input_sha256: str = Field(pattern=r'^[0-9a-f]{64}$')


def _hash(payload):
    # canonical_hash follows repository identity conventions; reject non-JSON
    # and nonfinite fixture metadata before using it for an integrity binding.
    json.dumps(payload, allow_nan=False)
    return canonical_hash(payload)


def _rows(columns, households):
    if not isinstance(columns, Mapping) or not columns:
        raise MembershipError('Resident columns are missing.')
    ids = columns.get('synthetic_id')
    if not isinstance(ids, (list, tuple)) or not ids:
        raise MembershipError('Nonempty existing resident IDs are required.')
    if any(not isinstance(i, str) or not i.strip() for i in ids) or len(set(ids)) != len(ids):
        raise MembershipError('Resident IDs must be nonempty and unique within the population.')
    if any(not isinstance(v, (list, tuple)) or len(v) != len(ids) for v in columns.values()):
        raise MembershipError('All resident columns must have equal lengths.')
    rows = sorted((dict(zip(columns, values)) for values in zip(*columns.values())),
                  key=lambda row: row['synthetic_id'])
    hrows = [asdict(r) for r in households.records]
    hids = [r.get('household_id') for r in hrows]
    if (not hids or any(not isinstance(i, str) or not i.strip() for i in hids)
            or len(set(hids)) != len(hids)):
        raise MembershipError('Household IDs must be nonempty and unique within the household build.')
    return rows, sorted(hrows, key=lambda row: row['household_id'])


def input_fingerprints(columns, manifest, households):
    """Bind all records and manifests, invariant to record/column mapping order.

    An integrity binding detects drift; it is not authentication or approval.
    No stored manifest hash is rewritten or assumed to authenticate fixture data.
    """
    try:
        rows, hrows = _rows(columns, households)
        return {'resident_input_sha256': _hash({'records': rows, 'manifest': manifest}),
                'household_input_sha256': _hash({'records': hrows, 'manifest': households.manifest})}
    except (AttributeError, TypeError, ValueError, OverflowError) as exc:
        raise MembershipError(f'Cannot fingerprint fixture inputs: {exc}') from exc


def assess_readiness(columns, manifest, households, *, reconciliation, contract):
    """Read-only gate with ready/blocked/not_assessable and stable reason codes.

    Both manifests must explicitly declare purpose=synthetic_fixture_only. This
    is an opt-in fixture assertion, never an authorization for official records.
    Unit weights alone do not establish an eligible unit-record representation.
    """
    reasons = []
    counts = {'residents': None, 'households': None, 'capacity': None}
    fingerprints = None

    def fail(code, detail, status='blocked'):
        reasons.append({'code': code, 'status': status, 'detail': detail})

    def result():
        status = ('blocked' if any(r['status'] == 'blocked' for r in reasons)
                  else 'not_assessable' if reasons else 'ready')
        return {'readiness_version': CONTRACT_VERSION, 'status': status,
                'ready': status == 'ready', 'reasons': reasons, 'counts': counts,
                'input_fingerprints': fingerprints, 'production_linking_enabled': False}

    try:
        if not isinstance(manifest, Mapping) or not isinstance(households.manifest, Mapping):
            raise ValueError('Manifests must be mappings.')
        rows, hrows = _rows(columns, households)
        fingerprints = input_fingerprints(columns, manifest, households)
        counts.update(residents=len(rows), households=len(hrows))
    except (AttributeError, TypeError, ValueError, OverflowError) as exc:
        fail('input_integrity', str(exc), 'not_assessable')
        return result()

    try:
        raw = contract.model_dump(mode='json') if isinstance(contract, FixtureMembershipContract) else contract
        contract = FixtureMembershipContract.model_validate(raw)
    except (TypeError, ValueError, ValidationError):
        fail('fixture_contract', 'Missing or malformed explicit fixture membership contract.', 'not_assessable')
        return result()

    if not all(m.get('purpose') == FIXTURE_PURPOSE for m in (manifest, households.manifest)):
        fail('fixture_only', 'Both builds must explicitly be intentionally constructed synthetic fixtures.')
    if (contract.population_id != manifest.get('population_id')
            or contract.household_population_id != households.manifest.get('household_population_id')):
        fail('build_identity', 'Contract build identities differ from the actual manifests.')
    if any(getattr(contract, key) != value for key, value in fingerprints.items()):
        fail('input_fingerprint', 'Fixture records or metadata changed after the explicit contract was bound.')
    if not contract.universe_approved:
        fail('universe_approval', 'Private-household fixture universe has not been explicitly approved.')
    universe = manifest.get('population_universe')
    if (not isinstance(universe, Mapping)
            or universe.get('definition') != 'ADNKS_private_household_residents'
            or not isinstance(universe.get('source_ref'), str) or not universe['source_ref'].strip()):
        fail('private_resident_eligibility', 'Require explicit private-household residents; aggregate institutional subtraction cannot identify individuals.',
             'not_assessable')
    ids = {r['synthetic_id'] for r in rows}
    eligible = contract.eligible_resident_ids
    if (any(not i.strip() for i in eligible) or len(set(eligible)) != len(eligible)
            or set(eligible) != ids or not contract.eligibility_source_ref.strip()):
        fail('eligibility', 'Eligibility evidence must identify every fixture resident exactly once, without missing or foreign references.')

    # Design weights also have to be explicitly unit weights. No normalization,
    # rounded weights, expanded virtual residents or implicit absence defaults.
    def unit(value):
        return type(value) in (int, float) and value == 1

    if any(not unit(r.get('population_weight')) or not unit(r.get('design_weight')) for r in rows):
        fail('resident_representation', 'Fixture linking requires explicit unit population AND design weights for every resident.')
    if any(not unit(r.get('household_weight')) for r in hrows):
        fail('household_representation', 'Fixture linking requires unit household weights, not aggregate representatives.')

    capacities = []
    for r in hrows:
        capacity = r.get('household_size')
        if (r.get('household_size_open_ended') is not False or r.get('household_size_class') == '10+'
                or type(capacity) is not int or capacity <= 0
                or type(r.get('household_size_lower')) is not int
                or type(r.get('household_size_upper')) is not int
                or r['household_size_lower'] != capacity or r['household_size_upper'] != capacity
                or r.get('household_size_class') != str(capacity)):
            fail('exact_capacity', 'Every household needs a closed, exact observed fixture capacity; open 10+ is unsupported.')
            break
        capacities.append(capacity)
    if len(capacities) == len(hrows):
        counts['capacity'] = sum(capacities)
        if counts['capacity'] != len(eligible):
            fail('capacity_mismatch', f"Exact capacity {counts['capacity']} differs from eligible resident count {len(eligible)}.")

    try:
        observed = reconcile(columns, manifest, households)
        if not isinstance(reconciliation, Mapping) or _hash(observed) != _hash(reconciliation):
            fail('reconciliation_binding', 'Supplied reconciliation must match a fresh assessment of these exact inputs.')
        if observed['status'] != 'compatible':
            fail('reconciliation_' + observed['status'], 'Aggregate reconciliation must be compatible before membership is ready.',
                 'not_assessable' if observed['status'] == 'not_assessable' else 'blocked')
    except (AttributeError, KeyError, TypeError, ValueError, OverflowError):
        fail('reconciliation_unavailable', 'Reconciliation could not be assessed for these inputs.', 'not_assessable')

    # Avoid crossing a local capacity boundary even when global totals match.
    try:
        resident_groups = Counter((r['province_code'], r['reference_year']) for r in rows)
        household_groups = Counter()
        if len(capacities) == len(hrows):
            for r, capacity in zip(hrows, capacities):
                household_groups[r['province_code'], r['reference_year']] += capacity
            if resident_groups != household_groups:
                fail('local_capacity', 'Exact capacity must match resident counts within each province/year.')
    except (KeyError, TypeError):
        fail('scope_metadata', 'Cannot establish province/year capacity groups.', 'not_assessable')
    return result()


def link_fixture(columns, manifest, households, *, reconciliation, contract,
                 config=None, enable_fixture_linking=False):
    """Assign only fully evidenced unit fixtures; blocked calls return no sidecar.

    Canonical resident IDs are shuffled using the existing versioned SHA stream
    separately per province/year. Canonical household IDs consume exact slots.
    Output records are sorted by resident ID and scoped by manifest.core.
    """
    if enable_fixture_linking is not True:
        raise MembershipError('Fixture membership is disabled; explicit enable_fixture_linking=True is required.')
    config = EnrichmentConfig.model_validate((config or EnrichmentConfig()).model_dump(mode='json'))
    readiness = assess_readiness(columns, manifest, households,
                                 reconciliation=reconciliation, contract=contract)
    if not readiness['ready']:
        raise MembershipError('Fixture membership refused: ' + ', '.join(r['code'] for r in readiness['reasons']), readiness)
    contract = FixtureMembershipContract.model_validate(
        contract.model_dump(mode='json') if isinstance(contract, FixtureMembershipContract) else contract)
    contract_payload = contract.model_dump(mode='json')
    contract_payload['eligible_resident_ids'] = sorted(contract_payload['eligible_resident_ids'])
    rows, hrows = _rows(columns, households)
    binding = {'population_id': manifest['population_id'], 'records_hash': _hash(rows)}
    hbinding = {'household_population_id': households.manifest['household_population_id'], 'records_hash': _hash(hrows)}
    profile = {'method_version': METHOD_VERSION, 'purpose': FIXTURE_PURPOSE,
               'evidence_class': 'synthetic_fixture', 'seed': config.seed,
               'stream_version': STREAM_VERSION, 'contract': contract_payload,
               'inputs': readiness['input_fingerprints'], 'limitations': list(LIMITATIONS)}
    profile_id = _hash(profile)
    assignments = {}
    for geo, year in sorted({(r['province_code'], r['reference_year']) for r in rows}):
        namespace = 'household-membership:' + METHOD_VERSION + ':' + _hash(
            [binding['population_id'], hbinding['household_population_id'], geo, year])
        residents = Stream(namespace, config.seed).shuffle(
            [r['synthetic_id'] for r in rows if (r['province_code'], r['reference_year']) == (geo, year)])
        offset = 0
        for h in hrows:
            if (h['province_code'], h['reference_year']) != (geo, year):
                continue
            for resident_id in residents[offset:offset + h['household_size']]:
                assignments[resident_id] = h['household_id']
            offset += h['household_size']
    records = tuple(ExtensionRecord(synthetic_id=resident_id, attributes=(AttributeValue(
        attribute='household_id', value=assignments[resident_id], status='assigned', provenance_profile=profile_id),))
                    for resident_id in sorted(assignments))
    m = {'schema_version': SCHEMA_VERSION, 'membership_contract_version': CONTRACT_VERSION,
         'model_version': METHOD_VERSION, 'purpose': FIXTURE_PURPOSE, 'core': binding,
         'households': hbinding, 'config': config.model_dump(mode='json'),
         'stream_version': STREAM_VERSION, 'input_fingerprints': readiness['input_fingerprints'],
         'reconciliation_sha256': _hash(reconciliation), 'readiness': readiness,
         'provenance_profiles': {profile_id: profile}, 'limitations': list(LIMITATIONS),
         'content_hash': _hash([r.model_dump(mode='json') for r in records])}
    m['artifact_id'] = 'ext-' + _hash(m)
    return ResidentExtension(records, m)


def validate_membership(extension, columns, manifest, households, *, reconciliation, contract):
    """Check references and replay the fixture method using existing sidecar models.

    No artifact is written. This narrow validator complements the existing
    artifact validators and is not the broader Validation Engine.
    """
    try:
        rows, hrows = _rows(columns, households)
        ids, hids = {r['synthetic_id'] for r in rows}, {r['household_id'] for r in hrows}
        observed = [r.synthetic_id for r in extension.records]
        if len(observed) != len(set(observed)) or set(observed) != ids:
            raise MembershipError('Missing, duplicate or foreign resident membership reference.')
        for r in extension.records:
            if (len(r.attributes) != 1 or r.attributes[0].attribute != 'household_id'
                    or r.attributes[0].value not in hids or r.attributes[0].status != 'assigned'):
                raise MembershipError('Missing/foreign household reference or unsupported membership attribute.')
        config = EnrichmentConfig.model_validate(extension.manifest['config'])
        expected = link_fixture(columns, manifest, households, reconciliation=reconciliation,
                                contract=contract, config=config, enable_fixture_linking=True)
        if extension.records != expected.records or extension.manifest != expected.manifest:
            raise MembershipError('Membership differs from deterministic replay, input binding or provenance.')
    except (AttributeError, KeyError, TypeError, ValueError) as exc:
        if isinstance(exc, MembershipError):
            raise
        raise MembershipError(f'Malformed membership sidecar: {exc}') from exc
    return {'membership_contract_version': CONTRACT_VERSION, 'valid': True,
            'records': len(extension.records), 'households': len(hrows),
            'purpose': FIXTURE_PURPOSE, 'production_linking_enabled': False}
